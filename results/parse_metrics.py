#!/usr/bin/env python3
"""
parse_metrics.py - Telemetry Parser & Statistical KPI Table Generator
Course: CCU Operating Systems (Fall 2026) - Term Project
Author: Quang-Huy Nguyen & Akash / An-Rui Peng

Parses the raw CSV files generated by dual_thread_bench and outputs
a publication-grade Markdown table comparing Config A (CFS) vs Config B (FIFO)
across 0%, 50%, and 100% stress levels for the Milestone 2 Progress Report.
"""

import sys
from pathlib import Path
import numpy as np

if sys.platform == "win32":
    sys.stdout.reconfigure(encoding="utf-8")

RESULTS_DIR = Path(__file__).resolve().parent / "raw"

def analyze_csv(csv_path: Path):
    if not csv_path.exists():
        return None

    # Columns: cycle,scheduled_ns,actual_wake_ns,lateness_ms,is_miss,is_starvation,setpoint,nivcsw,minflt
    data = np.genfromtxt(csv_path, delimiter=",", skip_header=1)
    if data.ndim == 1 and len(data) == 0:
        return None

    lateness = data[:, 3]
    is_miss = data[:, 4]
    is_starv = data[:, 5]
    nivcsw = data[:, 7]
    minflt = data[:, 8]

    n_cycles = len(lateness)
    avg_l = float(np.mean(lateness))
    min_l = float(np.min(lateness))
    max_l = float(np.max(lateness))
    p999_l = float(np.percentile(lateness, 99.9))
    jitter_sigma = float(np.std(lateness))
    miss_count = int(np.sum(is_miss))
    dmr = (miss_count / n_cycles) * 100.0
    starv_count = int(np.sum(is_starv))

    delta_nivcsw = int(nivcsw[-1] - nivcsw[0]) if len(nivcsw) > 1 else 0
    delta_minflt = int(minflt[-1] - minflt[0]) if len(minflt) > 1 else 0

    return {
        "n_cycles": n_cycles,
        "avg_l": avg_l,
        "min_l": min_l,
        "max_l": max_l,
        "p999_l": p999_l,
        "jitter_sigma": jitter_sigma,
        "miss_count": miss_count,
        "dmr": dmr,
        "starv_count": starv_count,
        "nivcsw": delta_nivcsw,
        "minflt": delta_minflt
    }

def main():
    print("=" * 88)
    print(" CCU OS Term Project: Preliminary Milestone 2 Results Summary")
    print("=" * 88)

    configs = ["A", "B"]
    stresses = [0, 50, 100]

    results = {}
    found_any = False

    for cfg in configs:
        for st in stresses:
            fname = f"config_{cfg}_stress_{st}.csv"
            fpath = RESULTS_DIR / fname
            metrics = analyze_csv(fpath)
            results[(cfg, st)] = metrics
            if metrics:
                found_any = True

    if not found_any:
        print(f"\n[Info] No benchmark CSV files found in {RESULTS_DIR}.")
        print("Run 'bash benchmarks/run_linux_experiments.sh' on the Linux board to generate data.")
        return

    print("\n| Config | Stress | Avg Lateness | WCL (Max) | P99.9 Tail | Jitter (σ) | DMR (%) | Misses | Invol Ctx Sw | Minor Faults |")
    print("|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|")

    for cfg in configs:
        cfg_label = "A (CFS)" if cfg == "A" else "B (FIFO 90)"
        for st in stresses:
            m = results.get((cfg, st))
            if m:
                print(f"| {cfg_label} | {st}% | {m['avg_l']:.3f} ms | {m['max_l']:.3f} ms | {m['p999_l']:.3f} ms | {m['jitter_sigma']:.3f} ms | {m['dmr']:.2f}% | {m['miss_count']} | {m['nivcsw']} | {m['minflt']} |")
            else:
                print(f"| {cfg_label} | {st}% | *(Pending)* | *(Pending)* | *(Pending)* | *(Pending)* | *(Pending)* | - | - | - |")

    print("\n" + "=" * 88)

if __name__ == "__main__":
    main()
